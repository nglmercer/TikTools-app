import { expect, test } from '@playwright/test';
import { emptyOverlay } from '../../src/shared/cloud-overlay-schema.ts';
import { countCalls, installFakeHost, readHostState, waitForFrontend } from './fixtures/tiktools-host.ts';
import { emptyState } from './fixtures/states.ts';

test('Overlay Changes revises the reviewed draft and restores it without preparing account sync', async ({ page }, testInfo) => {
  const state = emptyState();
  state.announcedMethods = ['cloud.status', 'bundles.overlays.create', 'bundles.overlays.read', 'bundles.overlays.revise'];
  state.sync = { signedIn: true, enabled: false, entries: [], resolved: [] };
  const id = '3f2c9a1e-8b7d-4c6e-9a0b-1d2e3f4a5b6c';
  state.overlay = { id, revision: 1, status: 'draft', document: emptyOverlay('chat', 'Saved overlay') };
  const capture = await installFakeHost(page, state);
  await page.goto('/#/overlays');
  await waitForFrontend(page);
  await page.getByRole('button', { name: 'Cloud', exact: true }).click();
  const library = page.getByRole('dialog', { name: 'Cloud overlays', exact: true });
  await library.getByRole('button', { name: 'Cloud editor', exact: true }).click();
  await library.getByRole('textbox', { name: 'Overlay id', exact: true }).fill(id);
  await library.getByRole('button', { name: 'Open', exact: true }).click();
  const name = library.getByRole('textbox', { name: 'Name', exact: true });
  await expect(name).toHaveValue('Saved overlay');
  await name.fill('Reviewed revision');
  await library.getByRole('button', { name: /Sync changes/ }).click();
  const changes = page.getByRole('dialog', { name: 'Changes · Overlays', exact: true });
  await expect(changes).toBeVisible();
  await expect(changes).not.toContainText('Prepare Cloud sync');
  await changes.getByRole('button', { name: 'Send (1)', exact: true }).click();
  await expect.poll(async () => (await readHostState(page)).overlay?.document.title).toBe('Reviewed revision');
  expect((await readHostState(page)).overlay?.revision).toBe(2);
  await changes.getByRole('button', { name: 'Close', exact: true }).click();
  await name.fill('Unsaved draft');
  await library.getByRole('button', { name: /Sync changes/ }).click();
  await changes.getByRole('button', { name: 'Use Cloud on this device', exact: true }).click();
  expect(await countCalls(page, 'bundles.overlays.revise')).toBe(1);
  await changes.getByRole('alertdialog').getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(name).toHaveValue('Reviewed revision');
  expect(await countCalls(page, 'bundles.overlays.revise')).toBe(1);
  expect(await countCalls(page, 'sync.v2.selected')).toBe(0);
  expect(await countCalls(page, 'sync.v2.migrate')).toBe(0);
  expect(await countCalls(page, 'sync.enable')).toBe(0);
  await page.screenshot({ path: testInfo.outputPath('overlay-changes.png') });
  capture.assertClean();
});
